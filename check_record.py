# -*- coding: utf-8 -*-
"""Run with Python: check recording choices and file safety without PSSE/wx."""
import os
import shutil
import sys
import tempfile
import types

wx = types.ModuleType('wx')
for index, name in enumerate(('ID_OK', 'ID_YES', 'ID_NO', 'ID_CANCEL', 'YES_NO',
                              'CANCEL', 'NO_DEFAULT', 'ICON_QUESTION')):
    setattr(wx, name, 1 << index)
sys.modules['wx'] = wx
import record


class Dialog(object):
    choice = wx.ID_YES

    def __init__(self, *args, **kwargs):
        self.name = kwargs.get('defaultValue')
        if not self.name:
            assert args[3] == ['Continue writing', 'Overwrite']

    def ShowModal(self):
        return wx.ID_CANCEL if not self.name and self.choice == wx.ID_CANCEL else wx.ID_OK

    def GetValue(self):
        return self.name

    def GetSelection(self):
        return 0 if self.choice == wx.ID_YES else 1

    def Destroy(self):
        pass


wx.TextEntryDialog = wx.SingleChoiceDialog = Dialog
NEW = (b'# File:"session.py", generated by PSSE\nimport psspy\n'
       b'_i = psspy.getdefaultint()\n'
       b'psspy.save("discard.sav")\npsspy.bus_data_3(123)\n'
       b'psspy.flat_2()\npsspy.fdns()\npsspy.fnsl()\npsspy.fnsl()\n')


class Psse(object):
    start_error = stop_error = 0

    def startrecording(self, format, path):
        assert format == 1
        self.path = path
        with open(path, 'wb') as output:
            output.write(NEW)
        return self.start_error

    def stoprecording(self):
        return self.stop_error


def read(path):
    with open(path, 'rb') as source:
        return source.read()


def write(path, content):
    with open(path, 'wb') as output:
        output.write(content)


def main():
    workspace = os.path.dirname(os.path.abspath(__file__))
    folder = tempfile.mkdtemp(prefix='check_record_', dir=workspace)
    try:
        path = os.path.join(folder, 'auto1.py')
        assert record.prompt_automation_path(None, folder) == (path, False)
        psse = Psse()
        recorder = record.PsseCommandRecorder(psse)
        recorder.start(path)
        assert recorder.is_recording and recorder.output_path == path
        assert not os.path.exists(path)
        assert recorder.stop() == path
        assert not recorder.is_recording and recorder.stop() is None
        cleaned = read(path)
        assert b'psspy.save(' not in cleaned
        assert cleaned.count(b'psspy.fnsl(') == 1
        for choice, expected in ((wx.ID_YES, (path, True)),
                                 (wx.ID_NO, (path, False)),
                                 (wx.ID_CANCEL, None)):
            Dialog.choice = choice
            assert record.prompt_automation_path(None, folder) == expected
            assert read(path) == cleaned

        original = (b'# Existing\nimport psspy\n_i = psspy.getdefaultint()\n'
                    b'psspy.save("keep.sav")\npsspy.fnsl()')
        write(path, original)
        recorder.start(path, append=True)
        assert read(path) == original
        recorder.stop()
        appended = read(path)
        assert appended.startswith(original + b'\n')
        assert appended.count(b'import psspy') == 1
        assert appended.count(b'getdefaultint') == 1
        assert appended.count(b'psspy.fnsl(') == 2
        assert b'# Add substation' in appended
        recorder.start(path)
        assert read(path) == appended
        recorder.stop()
        assert read(path) == cleaned

        write(path, b'')
        recorder.start(path, append=True)
        recorder.stop()
        assert read(path) == cleaned
        for append in (False, True):
            write(path, original)
            psse.start_error = 2
            try:
                recorder.start(path, append=append)
                assert False, 'start failure was ignored'
            except record.RecorderError:
                pass
            assert read(path) == original and not recorder.is_recording
            psse.start_error = 0
            recorder.start(path, append=append)
            psse.stop_error = 2
            try:
                recorder.stop()
                assert False, 'stop failure was ignored'
            except record.RecorderError:
                pass
            assert read(path) == original and not recorder.is_recording
            psse.stop_error = 0
            recorder.start(path, append=append)
            replace = record._replace_recording
            def fail_replace(source, destination):
                raise OSError('simulated locked destination')
            record._replace_recording = fail_replace
            try:
                try:
                    recorder.stop()
                    assert False, 'save failure was ignored'
                except record.RecorderError:
                    pass
                assert read(path) == original
                assert os.path.exists(psse.path)
            finally:
                record._replace_recording = replace
        print('PASS: choices, new file, append, overwrite, empty file, and failure safety')
    finally:
        assert os.path.dirname(os.path.realpath(folder)) == os.path.realpath(workspace)
        shutil.rmtree(folder)


if __name__ == '__main__':
    main()
